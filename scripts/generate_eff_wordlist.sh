#!/bin/bash
#
# Regenerates Sources/Core/Security/EFFWordlist.swift from the EFF large
# diceware wordlist. The list is embedded as Swift source (not an SPM
# resource) because the release bundler does not copy Core resource bundles.
#
# Usage: ./scripts/generate_eff_wordlist.sh [path/to/eff_large_wordlist.txt]
# With no argument the list is downloaded from eff.org.

set -euo pipefail

URL="https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt"
# SHA-256 of the published file (unchanged since 2016).
EXPECTED_SHA256="addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"
OUT="Sources/Core/Security/EFFWordlist.swift"

cd "$(dirname "$0")/.."

TMP="$(mktemp)"
trap 'rm -f "$TMP" "$TMP.words"' EXIT

if [ $# -ge 1 ]; then
    cp "$1" "$TMP"
else
    curl -sSfL -o "$TMP" "$URL"
fi

ACTUAL_SHA256="$(shasum -a 256 "$TMP" | awk '{print $1}')"
if [ "$ACTUAL_SHA256" != "$EXPECTED_SHA256" ]; then
    echo "error: checksum mismatch (got $ACTUAL_SHA256)" >&2
    exit 1
fi

# Every line must be "<5 dice digits>\t<word>"; keep only the word.
if awk -F'\t' 'NF != 2 || $1 !~ /^[1-6][1-6][1-6][1-6][1-6]$/ || $2 !~ /^[a-z-]+$/' "$TMP" | grep -q .; then
    echo "error: unexpected line format" >&2
    exit 1
fi
cut -f2 "$TMP" > "$TMP.words"

COUNT="$(wc -l < "$TMP.words" | tr -d ' ')"
UNIQUE="$(sort -u "$TMP.words" | wc -l | tr -d ' ')"
if [ "$COUNT" != "7776" ] || [ "$UNIQUE" != "7776" ]; then
    echo "error: expected 7776 unique words, got $COUNT ($UNIQUE unique)" >&2
    exit 1
fi

{
    echo "// Generated by scripts/generate_eff_wordlist.sh - do not edit by hand."
    echo "//"
    echo "// EFF large wordlist for passphrases (7,776 words, log2(7776) ~ 12.9 bits"
    echo "// per word). Source: $URL"
    echo "// Published by the Electronic Frontier Foundation under CC BY 3.0 US."
    echo ""
    echo "enum EFFWordlist {"
    echo "    /// The 7,776 words in dice-roll order (11111 ... 66666)."
    echo "    static let words: [String] = raw.split(separator: \"\\n\").map(String.init)"
    echo ""
    echo "    // A single string literal type-checks far faster than a 7,776-element"
    echo "    // array literal."
    echo "    private static let raw = \"\"\""
    cat "$TMP.words"
    echo "\"\"\""
    echo "}"
} > "$OUT"

echo "Wrote $OUT ($COUNT words)"
